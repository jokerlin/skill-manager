#!/bin/sh
# Write the Homebrew formula (CLI) and cask (app) for a release into a tap checkout.
#   sh scripts/homebrew.sh <version> <SHA256SUMS> <tap dir>
# The release workflow runs this after publishing and pushes the result to jokerlin/homebrew-tap.
set -eu
[ $# -eq 3 ] || { echo "usage: $0 <version> <SHA256SUMS> <tap dir>" >&2; exit 2; }
v=$1 sums=$2 tap=$3
base="https://github.com/jokerlin/skill-manager/releases/download/v$v"

sha() {
  s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "no checksum for $1 in $sums" >&2; exit 1; }
  echo "$s"
}

mkdir -p "$tap/Formula" "$tap/Casks"

cat > "$tap/Formula/skill-manager-cli.rb" <<EOF
# Generated by scripts/homebrew.sh in jokerlin/skill-manager. Do not edit by hand.
class SkillManagerCli < Formula
  desc "Manage agent skills across machines and harnesses (skm CLI and TUI)"
  homepage "https://github.com/jokerlin/skill-manager"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/skm-darwin-arm64"
      sha256 "$(sha skm-darwin-arm64)"
    end
    on_intel do
      url "$base/skm-darwin-x64"
      sha256 "$(sha skm-darwin-x64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/skm-linux-arm64"
      sha256 "$(sha skm-linux-arm64)"
    end
    on_intel do
      url "$base/skm-linux-x64"
      sha256 "$(sha skm-linux-x64)"
    end
  end

  conflicts_with "skm", because: "both install a \`skm\` binary"

  def install
    bin.install Dir["skm-*"].first => "skm"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/skm --version").strip
  end
end
EOF

cat > "$tap/Casks/skill-manager.rb" <<EOF
# Generated by scripts/homebrew.sh in jokerlin/skill-manager. Do not edit by hand.
cask "skill-manager" do
  arch arm: "arm64", intel: "x64"

  version "$v"
  sha256 arm:   "$(sha "skill-manager-$v-arm64-mac.zip")",
         intel: "$(sha "skill-manager-$v-x64-mac.zip")"

  url "$base/skill-manager-#{version}-#{arch}-mac.zip"
  name "Skill Manager"
  desc "Manage agent skills across machines and harnesses"
  homepage "https://github.com/jokerlin/skill-manager"

  # the app updates itself from signed GitHub releases
  auto_updates true
  depends_on macos: :ventura

  app "Skill Manager.app"

  # ~/.skm (the skill store and config) is yours and is never removed
  zap trash: [
    "~/Library/Application Support/Skill Manager",
    "~/Library/Application Support/skm",
    "~/Library/Preferences/dev.skm.app.plist",
    "~/Library/Saved Application State/dev.skm.app.savedState",
  ]
end
EOF

echo "wrote $tap/Formula/skill-manager-cli.rb and $tap/Casks/skill-manager.rb for $v"
